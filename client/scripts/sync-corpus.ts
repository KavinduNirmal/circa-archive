/**
 * Regenerates the client-bundled copy of the record corpus.
 *
 * `public/Ghost_story.md` is the published record and the file an editor
 * changes. A browser bundle cannot read a file, so the same document is carried
 * in `src/components/reader/ghost-story.ts` as data. This script is the only
 * writer of that bundle; `tests/ghost-story-sync.test.ts` holds the generator
 * and `tests/record-sources.test.ts` holds the bytes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const CORPUS_FILE = resolve(ROOT, "public/Ghost_story.md");
export const BUNDLE_FILE = resolve(ROOT, "src/components/reader/ghost-story.ts");

/** Escapes only what a template literal would otherwise reinterpret. */
export function escapeTemplate(value: string): string {
  return value.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

/** The whole generated module, header included, for one document. */
export function renderBundle(corpus: string): string {
  return `/**
 * The plan's test corpus, held as a string for the client.
 *
 * \`public/Ghost_story.md\` is the published copy, and the one the plan's probes
 * read from disk. A browser bundle cannot read a file, so the same document is
 * carried here as data. \`record-sources.test.ts\` holds the two byte-identical,
 * so the copy can never drift from the file it was taken from.
 *
 * Generated by \`scripts/sync-corpus.ts\`. Run \`bun run sync:corpus\` after editing
 * the published copy rather than editing this file by hand.
 */
export const GHOST_STORY = \`${escapeTemplate(corpus)}\`;
`;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const corpus = readFileSync(CORPUS_FILE, "utf8");
  const bundle = renderBundle(corpus);
  if (readFileSync(BUNDLE_FILE, "utf8") === bundle) {
    console.log("ghost-story.ts is already in sync with public/Ghost_story.md");
  } else {
    writeFileSync(BUNDLE_FILE, bundle);
    console.log("Wrote src/components/reader/ghost-story.ts from public/Ghost_story.md");
  }
}
